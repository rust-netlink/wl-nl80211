// while wpa_supplicant connected to hostapd APs on mac80211_hwsim:
//
//  * `/tmp/nl80211_task1.pcap` — WPA2-PSK "Test-WIFI" connection
//  * `/tmp/nl80211_sae.pcap` — WPA3-SAE "Test-WIFI" connection
//  * `/tmp/nl80211_events.pcap` — scan (`iw dev wlan0 scan`) + WPA2-PSK
//    connection + disconnect, with hostapd in the same netns (frame events)
//
// Each `raw` blob is a full netlink message as captured (nlmsghdr with the
// dynamic nl80211 family id 0x32, genl header, then attributes). The tests
// deserialize the message and verify [`crate::Nl80211Event::parse`]
// produces the expected typed event.

